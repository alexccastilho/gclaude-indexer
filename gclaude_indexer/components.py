"""Components downloaded on demand (2.0.0).

Some formats need data or programs the installer does not bring: every
Tesseract language and script, and (Tasks 9 and 11) a portable LibreOffice,
ffmpeg, whisper.cpp and its models. Each one is downloaded the first time it
is needed, into this machine's private folder (`paths.machine_local_folder`,
never the Drive-synced one, never anything that needs elevation).

Only what is in the manifest is ever downloaded. The manifest is a set of
JSON files in `manifests/`, shipped with the package; every entry has a
pinned HTTPS URL, the SHA-256 and the size of the file, its licence, its
kind (`file`: one file; `zip`: an archive extracted into a folder) and its
destination inside the private folder. `tessdata_fast.json` is generated by
`tools/gerar_manifesto_tessdata.py`; the other tasks add their own files.

How a download is made safe:
- it goes to `<destination>.part` and only becomes the real file after the
  size and the SHA-256 match; anything else deletes the `.part`;
- it is cut off as soon as it passes the manifest size (a server that sends
  more than promised never fills the disk);
- a ZIP has every member checked before anything is extracted (no absolute
  path, drive letter or `..`), has its member count and its total
  uncompressed size capped (`max_members`, `max_extracted`: a small archive
  that swells into the whole disk is refused), is extracted into a sibling
  folder and only then renamed over the destination;
- a redirect to anything but HTTPS is refused (the pinned URL is HTTPS, a
  mirror that bounces to plain HTTP would put the download in the clear);
- one lock per component: two conversions asking for the same language at
  once download it once, and a large download never holds up a small one.

`ensure` never raises: a component it could not get is `unavailable`, and
the caller decides what to do (the conversion marks the file to be done
again later — see `conversion.convert`).
"""

from __future__ import annotations

import hashlib
import json
import shutil
import threading
import urllib.error
import urllib.request
import zipfile
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path, PurePosixPath
from urllib.parse import urlparse

from .paths import machine_local_folder, resolve_within

MANIFEST_FOLDER = Path(__file__).resolve().parent / "manifests"
MANIFEST_FORMAT = 1
KINDS = ("file", "zip")

STATUS_PRESENT = "present"  # already on disk, nothing done
STATUS_INSTALLED = "installed"  # downloaded and verified now
STATUS_UNAVAILABLE = "unavailable"  # no network, bad hash, unknown name…

# Written inside an extracted folder once it is complete: an interrupted
# extraction never looks installed.
ZIP_MARKER_NAME = ".gclaude-component.json"

# A ZIP component that does not state its own ceilings may swell to this many
# times its size and hold this many members. LibreOffice, the largest, is
# well inside both; an entry that needs more says so in the manifest.
DEFAULT_EXTRACTED_FACTOR = 8
DEFAULT_MAX_MEMBERS = 20_000

_DOWNLOAD_TIMEOUT_S = 120
_BLOCK = 1 << 20


@dataclass(frozen=True)
class Component:
    name: str
    url: str
    sha256: str
    size: int
    license: str
    kind: str
    target: str
    # Only for `zip`: ceilings on the extraction (0 = the defaults above).
    max_extracted: int = 0
    max_members: int = 0

    @property
    def extracted_limit(self) -> int:
        return self.max_extracted or self.size * DEFAULT_EXTRACTED_FACTOR

    @property
    def members_limit(self) -> int:
        return self.max_members or DEFAULT_MAX_MEMBERS


@dataclass(frozen=True)
class InstalledComponent:
    name: str
    size: int
    license: str


# --- manifest ----------------------------------------------------------------


def _check_target(target: str) -> None:
    """A destination is a plain relative path with `/`: no drive, no root,
    no `..`, no backslash — checked here, and again on disk by
    `resolve_within` when it is used."""
    if not target or "\\" in target or ":" in target:
        raise ValueError(f"destino inválido no manifesto: {target!r}")
    path = PurePosixPath(target)
    if path.is_absolute() or any(part in ("", ".", "..") for part in target.split("/")):
        raise ValueError(f"destino inválido no manifesto: {target!r}")


def _parse_entry(entry: dict) -> Component:
    component = Component(
        name=str(entry["name"]),
        url=str(entry["url"]),
        sha256=str(entry["sha256"]).lower(),
        size=int(entry["size"]),
        license=str(entry["license"]),
        kind=str(entry["kind"]),
        target=str(entry["target"]),
        max_extracted=int(entry.get("max_extracted", 0)),
        max_members=int(entry.get("max_members", 0)),
    )
    if component.max_extracted < 0 or component.max_members < 0:
        raise ValueError(f"{component.name}: limite de extração inválido")
    parsed = urlparse(component.url)
    if parsed.scheme != "https" or not parsed.netloc:
        raise ValueError(f"{component.name}: só HTTPS é aceito ({component.url!r})")
    if len(component.sha256) != 64 or any(ch not in "0123456789abcdef" for ch in component.sha256):
        raise ValueError(f"{component.name}: SHA-256 inválido")
    if component.size <= 0:
        raise ValueError(f"{component.name}: tamanho inválido")
    if component.kind not in KINDS:
        raise ValueError(f"{component.name}: tipo desconhecido {component.kind!r}")
    if not component.license:
        raise ValueError(f"{component.name}: sem licença")
    _check_target(component.target)
    return component


def load_manifest(folder: Path | None = None) -> dict[str, Component]:
    """Every entry of every `*.json` in `folder` (the package's `manifests/`
    by default). A repeated name or a malformed entry is a packaging error
    and raises: it must never reach a user."""
    folder = MANIFEST_FOLDER if folder is None else folder
    components: dict[str, Component] = {}
    for path in sorted(folder.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        if data.get("format") != MANIFEST_FORMAT:
            raise ValueError(f"{path.name}: formato de manifesto desconhecido {data.get('format')!r}")
        for entry in data.get("components", []):
            component = _parse_entry(entry)
            if component.name in components:
                raise ValueError(f"{path.name}: componente repetido {component.name!r}")
            components[component.name] = component
    return components


@lru_cache(maxsize=1)
def manifest() -> dict[str, Component]:
    return load_manifest()


def get(name: str) -> Component | None:
    return manifest().get(name)


# --- where things are --------------------------------------------------------


def private_root() -> Path:
    return machine_local_folder()


def target_path(component: Component) -> Path:
    """The destination on disk, always inside the private folder."""
    return resolve_within(private_root(), component.target)


def is_installed(component: Component) -> bool:
    try:
        target = target_path(component)
    except ValueError:
        return False
    if component.kind == "zip":
        return (target / ZIP_MARKER_NAME).is_file()
    return target.is_file()


def path_of(name: str) -> Path | None:
    """Where an installed component is, or `None` (unknown or absent) —
    what a caller uses after `ensure`."""
    component = get(name)
    if component is None or not is_installed(component):
        return None
    return target_path(component)


# --- download ----------------------------------------------------------------

_locks_guard = threading.Lock()
_locks: dict[str, threading.Lock] = {}


def _lock_for(name: str) -> threading.Lock:
    with _locks_guard:
        return _locks.setdefault(name, threading.Lock())


class _HttpsOnlyRedirects(urllib.request.HTTPRedirectHandler):
    """A mirror may redirect, but never to anything that is not HTTPS: the
    manifest pins an HTTPS URL, and the hash would only catch the damage
    after the whole file went through the clear."""

    def redirect_request(self, req, fp, code, msg, headers, newurl):
        if urlparse(newurl).scheme != "https":
            raise urllib.error.URLError(f"redirecionamento para fora do HTTPS recusado: {newurl!r}")
        return super().redirect_request(req, fp, code, msg, headers, newurl)


_opener = urllib.request.build_opener(_HttpsOnlyRedirects())


def _open_url(url: str):
    """The only place this module touches the network (the test suite
    replaces it)."""
    return _opener.open(url, timeout=_DOWNLOAD_TIMEOUT_S)


def _download_to(component: Component, partial: Path) -> None:
    """Streams the file into `partial`, refusing it as soon as it passes the
    manifest size, then checks size and SHA-256. Raises on any problem."""
    digest = hashlib.sha256()
    written = 0
    with _open_url(component.url) as answer, partial.open("wb") as handle:
        while True:
            block = answer.read(_BLOCK)
            if not block:
                break
            written += len(block)
            if written > component.size:
                raise ValueError(f"{component.name}: maior que o tamanho do manifesto")
            digest.update(block)
            handle.write(block)
    if written != component.size:
        raise ValueError(f"{component.name}: {written} bytes, o manifesto diz {component.size}")
    if digest.hexdigest() != component.sha256:
        raise ValueError(f"{component.name}: SHA-256 não confere")


def _safe_members(archive: zipfile.ZipFile, component: Component | None = None) -> list[zipfile.ZipInfo]:
    """Refuses the whole archive if any member would land outside the
    destination (zip slip), or if it holds more members or swells to more
    bytes than the component allows — checked before anything is written."""
    members = archive.infolist()
    if component is not None:
        if len(members) > component.members_limit:
            raise ValueError(f"{component.name}: ZIP com membros demais ({len(members)})")
        if sum(member.file_size for member in members) > component.extracted_limit:
            raise ValueError(f"{component.name}: ZIP descomprimido passa do limite do manifesto")
    for member in members:
        name = member.filename
        if (
            not name
            or "\\" in name
            or ":" in name
            or name.startswith("/")
            or any(part == ".." for part in name.split("/"))
        ):
            raise ValueError(f"caminho inseguro no ZIP: {name!r}")
    return members


def _extract(component: Component, archive_path: Path, target: Path) -> None:
    staging = target.parent / (target.name + ".extracting")
    shutil.rmtree(staging, ignore_errors=True)
    staging.mkdir(parents=True)
    try:
        with zipfile.ZipFile(archive_path) as archive:
            members = _safe_members(archive, component)
            root = staging.resolve()
            for member in members:
                destination = (root / member.filename).resolve()
                if not destination.is_relative_to(root):
                    raise ValueError(f"caminho inseguro no ZIP: {member.filename!r}")
            archive.extractall(staging, members=members)
        (staging / ZIP_MARKER_NAME).write_text(
            json.dumps({"name": component.name, "sha256": component.sha256}), encoding="utf-8"
        )
        if target.exists():
            shutil.rmtree(target)
        staging.replace(target)
    except BaseException:
        shutil.rmtree(staging, ignore_errors=True)
        raise


def _install(component: Component) -> None:
    target = target_path(component)
    target.parent.mkdir(parents=True, exist_ok=True)
    # `name + ".part"`, not `with_suffix`: "script/Latin.traineddata" and a
    # future "model.v2.bin" keep their whole name.
    partial = target.parent / (target.name + ".part")
    try:
        _download_to(component, partial)
        if component.kind == "zip":
            _extract(component, partial, target)
        else:
            partial.replace(target)
    finally:
        partial.unlink(missing_ok=True)


def _changed() -> None:
    """What other modules cached about what is installed is stale now."""
    try:
        from .settings_proposal import installed_ocr_languages

        installed_ocr_languages.cache_clear()
    except Exception:
        pass


def ensure(names, download: bool = True) -> dict[str, str]:
    """Makes each component available, downloading what is missing (when
    `download`), and returns `{name: status}` — `present`, `installed` or
    `unavailable`. Never raises."""
    statuses: dict[str, str] = {}
    changed = False
    for name in dict.fromkeys(names):
        component = get(name)
        if component is None:
            statuses[name] = STATUS_UNAVAILABLE
            continue
        with _lock_for(name):
            # Checked again under the lock: whoever waited for it finds the
            # component the other thread has just installed.
            if is_installed(component):
                statuses[name] = STATUS_PRESENT
                continue
            if not download:
                statuses[name] = STATUS_UNAVAILABLE
                continue
            try:
                _install(component)
            except Exception:
                statuses[name] = STATUS_UNAVAILABLE
                continue
            statuses[name] = STATUS_INSTALLED if is_installed(component) else STATUS_UNAVAILABLE
            changed = True
    if changed:
        _changed()
    return statuses


# --- the components screen ---------------------------------------------------


def _size_on_disk(path: Path) -> int:
    if path.is_file():
        return path.stat().st_size
    total = 0
    for item in path.rglob("*"):
        try:
            if item.is_file():
                total += item.stat().st_size
        except OSError:
            pass
    return total


def installed_components() -> list[InstalledComponent]:
    """What is on disk now, with the size it takes, by name."""
    found = []
    for component in manifest().values():
        if not is_installed(component):
            continue
        try:
            size = _size_on_disk(target_path(component))
        except OSError:
            continue
        found.append(InstalledComponent(component.name, size, component.license))
    return sorted(found, key=lambda item: item.name)


def remove(name: str) -> bool:
    """Deletes an installed component — only a manifest entry, and only
    inside the private folder. `False` when there was nothing to remove or
    Windows refused (a file in use)."""
    component = get(name)
    if component is None:
        return False
    with _lock_for(name):
        if not is_installed(component):
            return False
        try:
            target = target_path(component)
            if not target.resolve().is_relative_to(private_root().resolve()):
                return False
            if component.kind == "zip":
                shutil.rmtree(target)
            else:
                target.unlink()
        except (OSError, ValueError):
            return False
    _changed()
    return True
