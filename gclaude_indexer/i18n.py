"""Internationalization table (user request): Brazilian Portuguese, English
and Spanish. Lives in core, not `web/`, because the web layer is not the
only writer of user-facing text — `artifacts.py` and `windows_prep.py`
(core) translate the four output artifacts and `CLAUDE.md` into the
interface's language too, and core must never import
from `web/`. `web/i18n.py` re-exports what the web layer needs
(`LANGUAGE_COOKIE_NAME` stays there — it is an HTTP concept, not a
translation concept) so existing imports (`from .i18n import ...` in
`web/app.py`) keep working unchanged.

Covers the interface's fixed text (titles, labels, buttons, help), the
fixed prose of the generated artifacts, and — since Task 12 —
the execution log's own messages: `record_event` (`events.py`) stores a
`log.*` key plus parameters and renders `event.message` from this table at
write time (for the on-disk log file, which needs text right away) and
again at read time (`list_events`, for whatever language the interface is
in *now*, which may differ from the one running at write time). A handful
of validation error messages one level down (e.g. inside
`classification.validate_item`) are still produced as plain Portuguese
text and only interpolated as opaque parameter values into a `log.*`
template — translating those too was judged out of this task's scope
(see `task-12-report.md`), unlike the ~48 `record_event` call sites
themselves, which are all key-based now.

The KEYS below were translated to English — e.g.
`novo_projeto.titulo` became `new_project.title`. The VALUES were not: each
locale's text stays in its own language (pt/en/es), because translating a
key is not translating its content.

A few key segments used to keep their original Portuguese token where they
mirrored an enum-like value defined outside this module (e.g. `theme.claro`,
`layout.padrao`) — Task 9c left those out on purpose, reasoning
they were purely internal tokens with no user-visible effect. Task 9d (same
phase) reversed that call: the project already had inconsistent precedent
(`diagnostics.key.*`, covered below, and `step_state.STATUSES` were both
translated despite the same argument applying to them), and the "internal
token" argument was itself undercut by the codebase-wide push for English
identifiers — `theme.py`/`layout.py` are exactly the kind of file an outside
contributor opens first. See those two modules for the full reasoning; the
keys here now read `theme.light`, `layout.standard`, etc. `diagnostics.key.*`
used to be one such case too (`tessdata_por`, `modelo_padrao`, ...) until
Task 9c translated `install_diagnostics.py`'s own key values along
with it — see that module for the current set.

Moved here from `web/i18n.py`: the table used to live
in the web layer only, which worked while only the interface itself needed
translating. It stopped working once the four output artifacts and
`CLAUDE.md` — generated by core modules — needed to follow the same
language, since core code must not import from `web/`.
"""

