# Reference table for a key missing from the current language, used by
# `translate()` below. Decision (Task 10, Phase 14): kept as the literal
# `"pt"`, independent of `DEFAULT_LANGUAGE`, now that the default varies
# with the detected Windows language instead of always being `"pt"`.
#
# Tying the reserve to `DEFAULT_LANGUAGE` instead would make it depend on
# which machine is running: on a Spanish-language Windows (`DEFAULT_LANGUAGE
# == "es"`), a key missing from `es` would fall back to `es` itself — i.e.
# not fall back at all, silently showing the raw key instead of readable
# text, on that machine only. `pt` is this project's original language and
# the one new keys are always written to first (see
# `test_os_tres_idiomas_tem_exatamente_as_mesmas_chaves`, which already
# treats it as the source of truth for key parity across all three tables),
# so it is the table guaranteed complete regardless of the runtime default.
# A key missing from `pt` too is a real defect: `translate()` then falls
# back to returning the raw key itself (see below), which shows up as
# visibly untranslated text instead of raising and taking a whole page
# down over one missing string.
_REFERENCE_LANGUAGE = "pt"


def valid_language(language: str | None) -> str:
    return language if language in _TRANSLATIONS else DEFAULT_LANGUAGE


_NESTED_KEY_MARKER = "$i18n_key"
_NESTED_PARAMS_MARKER = "$i18n_params"


def nested(key: str, **params) -> dict:
    """Marks `key` (+ `params`) as a parameter value that is itself a
    translation key, to resolve at render time — not literal text.

    Some `log.*` templates (`events.py`) embed a sub-fragment that is
    itself language-dependent (a yes/no label, "real size" vs. "estimated
    size", one item-rejection reason among several possible ones). Passing
    the already-rendered text as that parameter — e.g.
    `translate(language, "log.common.yes")` computed once in Python before
    calling `record_event` — freezes it in whatever language was current
    at write time: the *outer* message still retranslates correctly on a
    later read (`list_events`), but that inner fragment does not, which
    silently defeats this task's whole point for exactly the words most
    likely to be reused across templates. Wrap the inner key (and its own
    params, if it takes any) in this call instead of pre-translating it;
    `record_event`/`list_events` resolve it — via `has_key`/`translate`,
    recursively — every time the outer message is rendered, in whichever
    language that render asked for."""
    return {_NESTED_KEY_MARKER: key, _NESTED_PARAMS_MARKER: params}


def has_key(key: str) -> bool:
    """Whether `key` is a real translation key (present in the reference
    table, `pt` — see `_REFERENCE_LANGUAGE` above).

    Used by `events.record_event` (Task 12, Phase 14) to tell a genuine
    `log.*` key from arbitrary literal text passed as the same argument
    (ad hoc/legacy events, and direct test calls that predate this task) —
    literal text has no entry here and is stored/shown as-is, unchanged by
    language."""
    return key in _TRANSLATIONS[_REFERENCE_LANGUAGE]


def translate(language: str, key: str, **variables) -> str:
    table = _TRANSLATIONS.get(language, _TRANSLATIONS[DEFAULT_LANGUAGE])
    text = table.get(key, _TRANSLATIONS[_REFERENCE_LANGUAGE].get(key, key))
    if variables:
        try:
            return text.format(**variables)
        except (KeyError, IndexError):
            return text
    return text
