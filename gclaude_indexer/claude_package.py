# Fixed English name, like the four artifacts: a file name that
# changed with the interface language would break any link or script that
# points at it, and the guide's own *content* is what carries the language.
GUIDE_FILENAME = "HOW_TO_USE.md"


# Limite por arquivo de conhecimento de um Projeto do Claude (claude.ai),
# medido: um arquivo maior é recusado no envio. Fase 38: um
# arquivo acima disto não entra mais no pacote (`package_plan`); até a
# 1.7.5 ele entrava e a tela só avisava. A outra recusa conhecida é a da
# capacidade total do Project (dois arquivos de legislação de dezenas de
# MB, "o conhecimento do projeto excede o máximo"), que é o que
# `package_token_limit` e o nível `over` medem.
MAX_FILE_BYTES = 30 * 1024 * 1024

# Acima disto o Projeto liga a busca automática (RAG) em vez de manter os
# arquivos inteiros no contexto: ainda funciona, mas o Claude passa a ver
# trechos, não o índice inteiro.
RAG_THRESHOLD_TOKENS = 500_000

# Caracteres por token do Claude em markdown tabular em português: 3 a 3,5
# medidos; 3,0 é o lado conservador. Não confundir com o 1,45 da fase 21
# (`engine_local.py`), que mede o tokenizador do modelo local — com ele os
# poucos MB de um acervo grande já enxuto "estourariam" 2 milhões de
# tokens, e a tela avisaria em vermelho um pacote que cabe.
CLAUDE_CHARS_PER_TOKEN = 3.0


@dataclass(frozen=True)
class BudgetEntry:
    """Um arquivo do pacote: tamanho, tokens estimados e se passa do limite
    por arquivo do Projeto."""

    name: str
    size_bytes: int
    tokens: int
    too_big: bool


@dataclass(frozen=True)
class PackageBudget:
    """O pacote inteiro contra a capacidade do Projeto. `level`: `ok`;
    `rag` acima de `RAG_THRESHOLD_TOKENS`; `over` acima de
    `config.package_token_limit`. Só informa — nunca bloqueia."""

    entries: list[BudgetEntry]
    total_tokens: int
    limit_tokens: int
    level: str
    # Gerados na pasta de saída mas fora do ZIP: `timeline-<grupo>.md`. A
    # tela diz que existem e podem ser enviados à parte; não entram no total.
    outside: list[BudgetEntry] = field(default_factory=list)
    # Fase 38: acima de `MAX_FILE_BYTES`, fora do ZIP e fora do total. A
    # tela os lista em vermelho, com o que fazer.
    excluded: list[BudgetEntry] = field(default_factory=list)


@dataclass(frozen=True)
class PackagePlan:
    """O que entra no ZIP e o que ficou de fora por tamanho."""

    included: list[Path]
    excluded: list[BudgetEntry]


def _measure(path: Path) -> BudgetEntry | None:
    """Tokens pelo tamanho em bytes: ler 46 MB a cada abertura da tela de
    resultado para contar caracteres custaria segundos, e em tabela de
    português a diferença fica em ~2%, abaixo do erro da própria razão.
    `None` quando o arquivo sumiu entre o glob e o stat (a limpeza de
    órfãos de uma regeneração em curso): não é erro 500 na tela."""
    try:
        size = path.stat().st_size
    except OSError:
        return None
    return BudgetEntry(
        name=path.name, size_bytes=size, tokens=int(size / CLAUDE_CHARS_PER_TOKEN), too_big=size > MAX_FILE_BYTES,
    )


def candidate_files(config: ProjectConfig) -> list[Path]:
    """Os arquivos que o pacote quer levar, em ordem estável, antes do
    corte por tamanho: os artefatos fixos e os índices por grupo (fase 21 —
    o `index.md` virou sumário: sem eles, o pacote leva o mapa e deixa o
    território para trás). A cronologia por grupo fica de fora (ver
    `outside_files`)."""
    output_folder = Path(config.output_folder)
    arquivos = [output_folder / nome for nome in ARTIFACT_NAMES if (output_folder / nome).exists()]
    arquivos += sorted(output_folder.glob("index-*.md"))
    return arquivos


def package_plan(config: ProjectConfig) -> PackagePlan:
    """A lista única que o ZIP e o orçamento leem (fase 31), já sem o que
    o Project recusaria: um arquivo acima de `MAX_FILE_BYTES` fica em
    `excluded` em vez de ir no ZIP para ser recusado no envio (fase 38)."""
    included: list[Path] = []
    excluded: list[BudgetEntry] = []
    for path in candidate_files(config):
        entry = _measure(path)
        if entry is None:
            continue
        if entry.too_big:
            excluded.append(entry)
        else:
            included.append(path)
    return PackagePlan(included=included, excluded=excluded)


def package_files(config: ProjectConfig) -> list[Path]:
    """O que vai para o ZIP: `package_plan(config).included`."""
    return package_plan(config).included


def budget(config: ProjectConfig) -> PackageBudget:
    """Mede exatamente o que o ZIP leva (`package_plan`), mais o que ficou
    fora e o que nunca entra (`outside_files`)."""
    plan = package_plan(config)
    entries = [entry for entry in (_measure(path) for path in plan.included) if entry is not None]
    outside = [entry for entry in (_measure(path) for path in outside_files(config)) if entry is not None]
    total = sum(entry.tokens for entry in entries)
    if total > config.package_token_limit:
        level = "over"
    elif total > RAG_THRESHOLD_TOKENS:
        level = "rag"
    else:
        level = "ok"
    return PackageBudget(
        entries=entries, total_tokens=total, limit_tokens=config.package_token_limit, level=level,
        outside=outside, excluded=plan.excluded,
    )


def outside_files(config: ProjectConfig) -> list[Path]:
    """Gerados na pasta de saída e deixados fora do ZIP, para a tela dizer
    que existem. `timeline-<grupo>.md` sempre: num acervo grande ele
    repetia o índice do grupo reordenado por data, com centenas de milhares
    de tokens, e sozinho levava o pacote para além de 2 milhões de tokens."""
    output_folder = Path(config.output_folder)
    return sorted(output_folder.glob("timeline-*.md"))


def generate_claude_project_package(config: ProjectConfig, language: str) -> bytes:
    """Builds the `.zip` in memory — never writes anything to disk beyond
    what is already in `output_folder`, so no cleanup is needed afterwards."""
    guide = _GUIDE.get(language, _GUIDE["pt"]).format(name=config.name)

    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as zip_file:
        zip_file.writestr(GUIDE_FILENAME, guide)
        for path in package_files(config):
            zip_file.write(path, arcname=path.name)

    return buffer.getvalue()
